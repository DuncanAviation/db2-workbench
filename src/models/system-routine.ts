// One row of QSYS2.SYSROUTINES - a procedure or a function. Both kinds come from the one list query
// (CatalogQueries.listRoutines) and share one cache, so a procedure list and a function list are two
// filters over the same rows (MemoryCache.getProcedures/getFunctions) rather than two queries.
//
// `name` is ROUTINE_NAME - what a statement calls the routine by. `specificName` is SPECIFIC_NAME, the
// routine's unique identity within its schema: it is what SYSPARMS and the routine's own row are keyed
// by, and the only thing that tells two overloads of one function apart. The two are usually equal, but
// not for an overload or a routine whose specific name the system generated, so never use one for the other.
//
// `schema` is SPECIFIC_SCHEMA, the same form the procedure lookups have always used.
//
// Only the fields the tree, content assist and CALL resolution need are listed here. The rest of the row
// (behavior, dates, the body) is read one routine at a time - see SystemRoutineDetail.
export interface SystemRoutine {
	schema: string;
	name: string;
	specificName: string;
	/** Long SQL schema name (ROUTINE_SCHEMA). */
	sqlSchema: string;
	routineType: SystemRoutine.RoutineType;
	/** Functions only: scalar, table or aggregate. */
	functionType?: SystemRoutine.FunctionType;
	/** Functions only: how the function was created - see SystemRoutine.FunctionOrigin. */
	functionOrigin?: string;
	/** 'SQL' for a routine with an SQL body, 'EXTERNAL' for one that runs a program. */
	body: string;
	language: string;
	description: string;
	/** IN + OUT + INOUT parameters (a function's result isn't one). DB2 for i tells two procedures of
	 * one name apart by this count alone, so it is what picks the overload a CALL runs. */
	parameterCount: number;
}

export namespace SystemRoutine {
	export type RoutineType = 'PROCEDURE' | 'FUNCTION';

	/** SYSROUTINES.FUNCTION_TYPE. 'C' is a column (aggregate) function. */
	export type FunctionType = 'S' | 'T' | 'C';

	export enum FunctionOrigin {
		/** An external program. */
		EXTERNAL = 'E',
		/** Defined in SQL. */
		SQL = 'Q',
		/** Sourced on another function. */
		SOURCED = 'U',
		/** Generated by the system, e.g. the cast functions every distinct type gets. */
		SYSTEM_GENERATED = 'S'
	}
}

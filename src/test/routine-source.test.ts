import * as assert from 'assert';
import { extension } from '../extension.js';
import type { RoutineDdlErrorMessage, RoutineDdlLoadedMessage, RoutineSourceLoadedMessage } from '../webview-messages/schemas-messages.js';
import { TestSupport } from './test-support.js';

/**
 * The schema browser's routine Definition (full DDL) and Program Source tabs against the fake driver,
 * driven through SchemasProvider's handlers with a stand-in panel that records what is posted. As with the
 * other catalog tests, this proves the flow and the fixture's reading of the statements - not that
 * GENERATE_SQL, OBJECT_STATISTICS or BOUND_MODULE_INFO accept this exact SQL live.
 */
suite('Routine source against the fake driver', () => {
	let sequence = 0;
	let key = '';
	let posted: unknown[] = [];
	let panel = {
		webview: {
			postMessage: async (message: unknown) => {
				posted.push(message);
				return true;
			}
		}
	};

	setup(() => {
		key = `test://routine-source-${++sequence}`;
		posted = [];
	});

	suiteSetup(async () => {
		await TestSupport.activate();
	});

	teardown(async () => {
		await TestSupport.closeSessions(key);
	});

	const provider = () => <any>extension.schemasProvider;

	async function loadSource(specificName: string): Promise<RoutineSourceLoadedMessage> {
		await provider().postRoutineSource(panel, key, TestSupport.CONFIG_ID, 'SALES', specificName);
		return <RoutineSourceLoadedMessage>posted.at(-1);
	}

	test('a service program entry shows only the module that defines the entry', async () => {
		let reply = await loadSource('ORDER_HISTORY');

		assert.strictEqual(reply.command, 'routineSourceLoaded');
		assert.strictEqual(reply.program, 'SALES/ORDSRV (*SRVPGM)');
		assert.strictEqual(reply.entry, 'ORDHIST');
		assert.deepStrictEqual(reply.sources.map(source => source.module), ['ORDSRV02']);
		assert.strictEqual(reply.entryModuleFound, true);
		assert.ok(reply.sources[0].text?.includes('dcl-proc ordHist export;'));
	});

	test('a *LIBL program is found through the library list', async () => {
		let reply = await loadSource('ORDER_REPORT');

		assert.strictEqual(reply.program, 'SALES/ORDRPT (*PGM)');
		assert.strictEqual(reply.resolvedFromLibraryList, true);
		assert.deepStrictEqual(reply.sources.map(source => source.location), ['SALES/QRPGSRC(ORDRPT)']);
		assert.strictEqual(reply.unavailable, undefined);
	});

	test('a *LIBL program on no library-list schema names the libraries holding a copy', async () => {
		let reply = await loadSource('ORDER_EXPORT');

		assert.deepStrictEqual(reply.sources, []);
		assert.strictEqual(reply.program, '*LIBL/ORDEXP (*PGM)');
		assert.strictEqual(reply.unavailable, '*PGM ORDEXP was not found on the library list, so calling this procedure from this connection would fail. Copies exist in ARCHIVE.');
	});

	test('a program deleted since the routine was created is reported as missing', async () => {
		let reply = await loadSource('ORDER_PURGE');

		assert.deepStrictEqual(reply.sources, []);
		assert.match(reply.unavailable ?? '', /\*SRVPGM OLDLIB\/PURGESRV was not found/);
	});

	test('an SQL routine names no program', async () => {
		let reply = await loadSource('NEXT_ORDER_NUMBER');

		assert.strictEqual(reply.unavailable, 'No external program is recorded for this routine.');
	});

	test('the full DDL is generated by specific name, and a routine GENERATE_SQL cannot find is posted as an error', async () => {
		await provider().postRoutineDdl(panel, key, TestSupport.CONFIG_ID, { command: 'loadRoutineDdl', schema: 'SALES', table: 'ORDER_TOTAL_RECALC1', routineType: 'PROCEDURE' });
		let loaded = <RoutineDdlLoadedMessage>posted.at(-1);

		assert.strictEqual(loaded.command, 'routineDdlLoaded');
		assert.ok(loaded.ddl.startsWith('CREATE OR REPLACE PROCEDURE SALES.ORDER_TOTAL ('), loaded.ddl);
		assert.ok(loaded.ddl.includes('SPECIFIC SALES.ORDER_TOTAL_RECALC1'));

		await provider().postRoutineDdl(panel, key, TestSupport.CONFIG_ID, { command: 'loadRoutineDdl', schema: 'SALES', table: 'NOSUCH', routineType: 'PROCEDURE' });
		let failed = <RoutineDdlErrorMessage>posted.at(-1);

		assert.strictEqual(failed.command, 'routineDdlError');
		assert.ok(JSON.stringify(failed.error).includes('42704'));
	});
});
